"""Epistemic origin — how a thing came to be known, and therefore how it is checked.

The Knowledge Contract's central axis ([34-knowledge-contract.md](../../../../docs/architecture/34-knowledge-contract.md)),
expressed as a type because origin *determines the verification procedure*: a
reader checks a derivation by recomputing it and a model's output by comparing
it against something else. An object whose origin were merely documented would
be one whose check depended on a comment.

**Two members, not four, and the omission is the point.**

The contract names four origins — RECORDED, DERIVED, ATTESTED, INFERRED. This
module constructs two. The other two are absent because **no code here can
produce one**, and adding a member nothing constructs is a value that exists
only to be wrong later:

- **RECORDED** belongs to Provider Platform, which stores what a provider said.
  Research records nothing; it reads what other modules recorded.
- **ATTESTED** is external — *"a named source asserts X"* — and M10 was ruled
  **Internal Research** on 2026-07-31. There is no retrieval path to an outside
  party, so there is nothing here to attest.

The consequence is deliberate: **an ATTESTED research object is unconstructable,
not merely unbuilt.** A future milestone that adds external retrieval must add
the member, which is a visible diff on a file that says why it was absent —
rather than a field quietly acquiring a value nobody ruled on. That is the
ruling made mechanical, and it is enforced in the Security Invariants suite.

**There is deliberately no `citable` flag here.** Citability is expressed
structurally, one file over: a DERIVED finding exposes an `EvidenceRef`, and an
INFERRED synthesis exposes no address at all. A boolean beside that would be a
second representation of one truth, and the two would eventually disagree.
"""

from __future__ import annotations

from enum import StrEnum


class EpistemicOrigin(StrEnum):
    """The origin of one knowledge object. Exactly one, immutable for its life."""

    #: Deterministically computed from cited facts. **Fully verifiable** — the
    #: only class where a reader can check the content mechanically and
    #: totally, by recomputing it from the same inputs.
    DERIVED = "derived"

    #: Generated by a model. **Never verifiable in content**, only in act:
    #: which evidence, which prompt, which model, when. Never citable.
    INFERRED = "inferred"
